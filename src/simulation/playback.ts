import { CACHE_KINDS, MESSAGING_KINDS, type ComponentKind, type RequestRecord, type SimulationResult } from './engine';

/**
 * Read-only playback index built from engine output. Everything here is derived from recorded
 * request spans and failures; nothing feeds back into the simulation. Arrays are time-sorted so
 * the UI can answer "what is happening at simulated time t" with binary searches each frame.
 */

export type Outcome = 'success' | 'failed' | 'timeout' | 'unfinished';
export type OperationalState = 'idle' | 'processing' | 'queued' | 'near-capacity' | 'saturated' | 'failed';
export const OUTCOMES: Outcome[] = ['success', 'failed', 'timeout', 'unfinished'];

export const HOP_REQUEST = 0;
export const HOP_AFTER_MISS = 1;
export const HOP_JOB = 2;
export type HopKind = typeof HOP_REQUEST | typeof HOP_AFTER_MISS | typeof HOP_JOB;

/** Recorded transitions along one directed connection, plus the requests that ended at its target. */
export type Lane = {
  hopAt: Float64Array; hopRequest: Int32Array; hopKind: Uint8Array;
  endAt: Float64Array; endRequest: Int32Array; endOutcome: Uint8Array; endHit: Uint8Array;
};

export type ComponentTrack = {
  kind: ComponentKind | 'unknown'; capacity: number; queueLimit: number;
  /** Interval starts and ends, each sorted independently: open count at t = starts <= t minus ends <= t. */
  activeStart: Float64Array; activeEnd: Float64Array;
  queuedStart: Float64Array; queuedEnd: Float64Array;
  /** Rejections, timeouts and unroutable requests attributed to this component. */
  failures: Float64Array;
  success: Float64Array; failed: Float64Array; timeout: Float64Array;
  hits: Float64Array; misses: Float64Array;
  jobs: Float64Array;
  /** Arrivals generated by this component (clients only). */
  sent: Float64Array;
};

export const EVENT_TYPES = ['arrival', 'queued', 'processing', 'cache-hit', 'cache-miss', 'enqueued', 'job-start', 'job-done', 'success', 'failed', 'timeout', 'unfinished', 'dead-lettered'] as const;
export type TimelineEventType = typeof EVENT_TYPES[number];
export type TimelineEvent = { at: number; type: TimelineEventType; requestId: number; componentId?: string; jobId?: number };

export type PlaybackIndex = {
  durationMs: number;
  componentIds: string[];
  lanes: Record<string, Lane>;
  components: Record<string, ComponentTrack>;
  events: { at: Float64Array; type: Uint8Array; request: Int32Array; component: Int32Array; job: Int32Array };
  arrivals: Float64Array;
  finished: { success: Float64Array; failed: Float64Array; timeout: Float64Array; unfinished: Float64Array };
  series: { bucketMs: number; success: Uint32Array; failed: Uint32Array; timeout: Uint32Array; arrivals: Uint32Array };
  maxLatency: number;
};

export const laneKey = (source: string, target: string) => `${source}->${target}`;

const outcomeOf = (request: RequestRecord): Outcome | null =>
  request.status === 'completed' ? 'success'
    : request.status !== 'failed' ? null
      : request.failureKind === 'timeout' ? 'timeout' : request.failureKind === 'unfinished' ? 'unfinished' : 'failed';

const sorted = (values: number[]) => Float64Array.from(values).sort();

type LaneDraft = { hops: Array<[number, number, number]>; ends: Array<[number, number, number, number]> };
type TrackDraft = { active: Array<[number, number]>; queued: Array<[number, number]>; failures: number[]; success: number[]; failed: number[]; timeout: number[]; hits: number[]; misses: number[]; jobs: number[]; sent: number[] };

export function createPlaybackIndex(result: SimulationResult): PlaybackIndex {
  const kinds = new Map<string, ComponentKind>(result.components.map(metric => [metric.id, metric.kind]));
  const isCache = (id: string) => CACHE_KINDS.has(kinds.get(id) as ComponentKind);
  const isMessaging = (id: string) => MESSAGING_KINDS.has(kinds.get(id) as ComponentKind);
  const metrics = new Map(result.components.map(metric => [metric.id, metric]));
  const componentIds: string[] = []; const componentIndex = new Map<string, number>();
  const idOf = (id: string | undefined) => {
    if (id === undefined) return -1;
    let index = componentIndex.get(id); if (index === undefined) { index = componentIds.length; componentIds.push(id); componentIndex.set(id, index); }
    return index;
  };
  const lanes = new Map<string, LaneDraft>(); const tracks = new Map<string, TrackDraft>();
  const lane = (from: string, to: string) => { const key = laneKey(from, to); let draft = lanes.get(key); if (!draft) lanes.set(key, draft = { hops: [], ends: [] }); return draft; };
  const track = (id: string) => { let draft = tracks.get(id); if (!draft) tracks.set(id, draft = { active: [], queued: [], failures: [], success: [], failed: [], timeout: [], hits: [], misses: [], jobs: [], sent: [] }); return draft; };
  const events: Array<[number, number, number, number, number]> = [];
  const event = (at: number, type: TimelineEventType, request: number, component?: string, job = 0) => events.push([at, EVENT_TYPES.indexOf(type), request, idOf(component), job]);
  const arrivals: number[] = []; const finished: Record<Outcome, number[]> = { success: [], failed: [], timeout: [], unfinished: [] };
  let maxLatency = 0;

  /** Walks one record's spans and emits hops, occupancy intervals, outcomes and timeline events. */
  const walk = (record: RequestRecord, isJob: boolean) => {
    const timelineId = isJob ? record.parentId ?? record.id : record.id; const job = isJob ? record.id : 0;
    let previous = record.origin; let previousEnd = record.arrivalTime; let lastLane: LaneDraft | undefined;
    const lastCache = record.processing.reduce((last, span, index) => isCache(span.component) ? index : last, -1);
    // A redelivered job waits again from its redelivery time, not from its first dispatch.
    const readyAt = (until: number, from: number) => (record.redeliveredAt ?? []).reduce((latest, at) => at <= until && at > latest ? at : latest, from);
    let afterMiss = false;
    if (!isJob) { event(record.arrivalTime, 'arrival', record.id, record.origin); if (record.origin !== undefined) track(record.origin).sent.push(record.arrivalTime); }
    record.processing.forEach((span, index) => {
      if (previous !== undefined) { lastLane = lane(previous, span.component); lastLane.hops.push([previousEnd, record.id, isJob ? HOP_JOB : afterMiss ? HOP_AFTER_MISS : HOP_REQUEST]); }
      const target = track(span.component);
      const waitFrom = readyAt(span.start, previousEnd);
      if (span.start > waitFrom) { target.queued.push([waitFrom, span.start]); event(waitFrom, 'queued', timelineId, span.component, job); }
      target.active.push([span.start, span.end]);
      event(span.start, isJob ? 'job-start' : 'processing', timelineId, span.component, job);
      afterMiss = false;
      if (isCache(span.component)) {
        const hit = index === lastCache && record.cache === 'hit';
        (hit ? target.hits : target.misses).push(span.end); afterMiss = !hit;
        event(span.end, hit ? 'cache-hit' : 'cache-miss', timelineId, span.component);
      }
      if (isMessaging(span.component) && !isJob && record.status === 'completed' && index === record.processing.length - 1) { target.jobs.push(span.end); event(span.end, 'enqueued', timelineId, span.component); }
      previous = span.component; previousEnd = span.end;
    });
    // A request can fail at a component it reached but never started (queue full, timeout, waiting at the end).
    const failedAt = record.failedAt ?? (record.status === 'pending' ? record.destination : undefined);
    if (failedAt !== undefined && failedAt !== previous) {
      if (previous !== undefined) { lastLane = lane(previous, failedAt); lastLane.hops.push([previousEnd, record.id, isJob ? HOP_JOB : afterMiss ? HOP_AFTER_MISS : HOP_REQUEST]); }
      const end = record.completedAt ?? result.durationMs;
      const waitFrom = readyAt(end, previousEnd);
      if (end > waitFrom && record.failureKind !== 'rejected') track(failedAt).queued.push([waitFrom, end]);
      previous = failedAt;
    }
    const outcome = outcomeOf(record); if (!outcome || previous === undefined) return;
    const at = record.completedAt ?? result.durationMs; const target = track(previous);
    if (outcome === 'success') target.success.push(at); else if (outcome === 'timeout') target.timeout.push(at); else if (outcome === 'failed') target.failed.push(at);
    if (outcome === 'failed' || outcome === 'timeout') target.failures.push(at);
    lastLane?.ends.push([at, record.id, OUTCOMES.indexOf(outcome), outcome === 'success' && record.cache === 'hit' && isCache(previous) ? 1 : 0]);
    if (isJob) {
      if (outcome === 'success') event(at, 'job-done', timelineId, previous, job); else if (outcome !== 'unfinished') event(at, outcome, timelineId, previous, job);
      if (record.deadLetteredTo && record.origin) {
        lane(record.origin, record.deadLetteredTo).hops.push([at, record.id, HOP_JOB]); track(record.deadLetteredTo).jobs.push(at);
        event(at, 'dead-lettered', timelineId, record.deadLetteredTo, job);
      }
      return;
    }
    finished[outcome].push(at); if (record.latency !== undefined && outcome === 'success') maxLatency = Math.max(maxLatency, record.latency);
    event(at, outcome, record.id, previous);
  };

  for (const request of result.requests) { arrivals.push(request.arrivalTime); walk(request, false); }
  for (const job of result.jobs ?? []) walk(job, true);

  const order = events.map((_, index) => index).sort((a, b) => events[a][0] - events[b][0] || a - b);
  const bucketMs = Math.max(10, Math.ceil(result.durationMs / 120 / 10) * 10); const buckets = Math.max(1, Math.ceil(result.durationMs / bucketMs));
  const bucketize = (values: number[]) => { const counts = new Uint32Array(buckets); for (const at of values) counts[Math.min(buckets - 1, Math.floor(at / bucketMs))]++; return counts; };
  const intervals = (values: Array<[number, number]>) => ({ start: sorted(values.map(value => value[0])), end: sorted(values.map(value => value[1])) });

  const components: Record<string, ComponentTrack> = {};
  for (const id of new Set([...tracks.keys(), ...metrics.keys()])) {
    const draft = track(id); const metric = metrics.get(id); const active = intervals(draft.active); const queued = intervals(draft.queued);
    components[id] = {
      kind: kinds.get(id) ?? 'unknown', capacity: Math.max(1, Math.floor(metric?.capacity ?? 1)), queueLimit: metric?.queueLimit ?? 500,
      activeStart: active.start, activeEnd: active.end, queuedStart: queued.start, queuedEnd: queued.end,
      failures: sorted(draft.failures), success: sorted(draft.success), failed: sorted(draft.failed), timeout: sorted(draft.timeout), hits: sorted(draft.hits), misses: sorted(draft.misses), jobs: sorted(draft.jobs), sent: sorted(draft.sent),
    };
  }
  const laneRecord: Record<string, Lane> = {};
  for (const [key, draft] of lanes) {
    draft.hops.sort((a, b) => a[0] - b[0]); draft.ends.sort((a, b) => a[0] - b[0]);
    laneRecord[key] = {
      hopAt: Float64Array.from(draft.hops, hop => hop[0]), hopRequest: Int32Array.from(draft.hops, hop => hop[1]), hopKind: Uint8Array.from(draft.hops, hop => hop[2]),
      endAt: Float64Array.from(draft.ends, end => end[0]), endRequest: Int32Array.from(draft.ends, end => end[1]), endOutcome: Uint8Array.from(draft.ends, end => end[2]), endHit: Uint8Array.from(draft.ends, end => end[3]),
    };
  }
  return {
    durationMs: result.durationMs, componentIds, lanes: laneRecord, components,
    events: { at: Float64Array.from(order, index => events[index][0]), type: Uint8Array.from(order, index => events[index][1]), request: Int32Array.from(order, index => events[index][2]), component: Int32Array.from(order, index => events[index][3]), job: Int32Array.from(order, index => events[index][4]) },
    arrivals: sorted(arrivals),
    finished: { success: sorted(finished.success), failed: sorted(finished.failed), timeout: sorted(finished.timeout), unfinished: sorted(finished.unfinished) },
    series: { bucketMs, success: bucketize(finished.success), failed: bucketize(finished.failed), timeout: bucketize(finished.timeout), arrivals: bucketize(arrivals) },
    maxLatency,
  };
}

/** Number of values <= t in a sorted array. */
export function countUpTo(values: ArrayLike<number>, t: number) {
  let low = 0; let high = values.length;
  while (low < high) { const mid = (low + high) >> 1; if (values[mid] <= t) low = mid + 1; else high = mid; }
  return low;
}
/** Number of values < t in a sorted array. */
export function countBefore(values: ArrayLike<number>, t: number) {
  let low = 0; let high = values.length;
  while (low < high) { const mid = (low + high) >> 1; if (values[mid] < t) low = mid + 1; else high = mid; }
  return low;
}

/** Counts half-open intervals [start, end) containing t in O(log n), given independently sorted starts and ends. */
function openAt(start: Float64Array, end: Float64Array, t: number) {
  return countUpTo(start, t) - countUpTo(end, t);
}

export type ComponentLive = {
  state: OperationalState; active: number; queued: number; capacity: number; queueLimit: number; recentFailures: number;
  succeeded: number; failed: number; timedOut: number; hits: number; misses: number; jobs: number; sent: number;
};

/** Backlog at or above this share of the queue limit is shown as saturated. */
export const SATURATION_QUEUE_SHARE = 0.1;
/** Slot occupancy at or above this share (with more than one slot) is shown as near capacity. */
export const NEAR_CAPACITY_SHARE = 0.8;

export function componentLive(index: PlaybackIndex | null, id: string, t: number, failureWindowMs: number): ComponentLive | null {
  const track = index?.components[id]; if (!track) return null;
  const active = openAt(track.activeStart, track.activeEnd, t);
  const queued = openAt(track.queuedStart, track.queuedEnd, t);
  const recentFailures = countUpTo(track.failures, t) - countUpTo(track.failures, t - Math.max(1, failureWindowMs));
  const state: OperationalState = recentFailures > 0 ? 'failed'
    : queued > 0 && queued >= Math.max(1, Math.ceil(track.queueLimit * SATURATION_QUEUE_SHARE)) ? 'saturated'
      : queued > 0 ? 'queued'
        : track.capacity > 1 && active / track.capacity >= NEAR_CAPACITY_SHARE ? 'near-capacity'
          : active > 0 ? 'processing' : 'idle';
  return {
    state, active, queued, capacity: track.capacity, queueLimit: track.queueLimit, recentFailures,
    succeeded: countUpTo(track.success, t), failed: countUpTo(track.failed, t), timedOut: countUpTo(track.timeout, t),
    hits: countUpTo(track.hits, t), misses: countUpTo(track.misses, t), jobs: countUpTo(track.jobs, t), sent: countUpTo(track.sent, t),
  };
}

export type Particle = { requestId: number; kind: HopKind; progress: number };
export type Burst = { requestId: number; outcome: Outcome; cacheHit: boolean; progress: number };

/**
 * Requests on a connection at time t. The engine records transitions as instantaneous, so a
 * particle travels during a short visual window that ends exactly at the recorded arrival time.
 * When more than `limit` are in transit, an evenly spaced sample is returned (the total is reported).
 */
export function particlesAt(lane: Lane | undefined, t: number, windowMs: number, limit: number, pinned: number | null = null): { particles: Particle[]; total: number } {
  if (!lane || windowMs <= 0) return { particles: [], total: 0 };
  const from = countBefore(lane.hopAt, t); const to = countUpTo(lane.hopAt, t + windowMs); const total = to - from;
  const particles: Particle[] = []; const step = total > limit ? total / limit : 1;
  const push = (index: number) => particles.push({ requestId: lane.hopRequest[index], kind: lane.hopKind[index] as HopKind, progress: 1 - (lane.hopAt[index] - t) / windowMs });
  for (let cursor = 0; cursor < total && particles.length < limit; cursor += step) push(from + Math.floor(cursor));
  if (pinned !== null && step > 1) for (let index = from; index < to; index++) if (lane.hopRequest[index] === pinned) { if (!particles.some(particle => particle.requestId === pinned)) push(index); break; }
  return { particles, total };
}

/** Outcomes recorded at the connection's target during the last `windowMs` of simulated time. */
export function burstsAt(lane: Lane | undefined, t: number, windowMs: number, limit: number): Burst[] {
  if (!lane || windowMs <= 0) return [];
  const to = countUpTo(lane.endAt, t); const from = Math.max(countUpTo(lane.endAt, t - windowMs), to - limit); const bursts: Burst[] = [];
  for (let index = from; index < to; index++) bursts.push({ requestId: lane.endRequest[index], outcome: OUTCOMES[lane.endOutcome[index]], cacheHit: lane.endHit[index] === 1, progress: (t - lane.endAt[index]) / windowMs });
  return bursts;
}

/** The latest `count` timeline events at or before t, newest first. */
export function timelineAt(index: PlaybackIndex | null, t: number, count: number): TimelineEvent[] {
  if (!index) return [];
  const end = countUpTo(index.events.at, t); const list: TimelineEvent[] = [];
  for (let cursor = end - 1; cursor >= Math.max(0, end - count); cursor--) {
    const component = index.events.component[cursor]; const job = index.events.job[cursor];
    list.push({ at: index.events.at[cursor], type: EVENT_TYPES[index.events.type[cursor]], requestId: index.events.request[cursor], componentId: component >= 0 ? index.componentIds[component] : undefined, jobId: job || undefined });
  }
  return list;
}

export type LiveTotals = { arrived: number; inFlight: number; succeeded: number; failed: number; timedOut: number; unfinished: number };
export function totalsAt(index: PlaybackIndex | null, t: number): LiveTotals {
  if (!index) return { arrived: 0, inFlight: 0, succeeded: 0, failed: 0, timedOut: 0, unfinished: 0 };
  const arrived = countUpTo(index.arrivals, t); const succeeded = countUpTo(index.finished.success, t); const failed = countUpTo(index.finished.failed, t); const timedOut = countUpTo(index.finished.timeout, t);
  const unfinished = countUpTo(index.finished.unfinished, t);
  return { arrived, inFlight: Math.max(0, arrived - succeeded - failed - timedOut - unfinished), succeeded, failed, timedOut, unfinished };
}

export type RequestPhase = 'waiting' | 'in-flight' | Outcome;
/** The request's status as of simulated time t (the trace itself is the complete record). */
export function phaseAt(request: RequestRecord, t: number): RequestPhase {
  if (t < request.arrivalTime) return 'waiting';
  const outcome = outcomeOf(request); if (!outcome || request.completedAt === undefined || request.completedAt > t) return 'in-flight';
  return outcome;
}
export { outcomeOf };

export function findRequest(result: SimulationResult | null, id: number | null): RequestRecord | null {
  if (!result || id === null) return null;
  if (id < 0) return result.jobs?.[-id - 1] ?? null;
  const direct = result.requests[id]; if (direct?.id === id) return direct;
  let low = 0; let high = result.requests.length - 1;
  while (low <= high) { const mid = (low + high) >> 1; const value = result.requests[mid].id; if (value === id) return result.requests[mid]; if (value < id) low = mid + 1; else high = mid - 1; }
  return null;
}

export type TraceStep = { component: string; arrivedAt: number; start?: number; end?: number; wait: number; note?: string; result: 'processed' | 'routed' | 'cache-hit' | 'cache-miss' | 'enqueued' | 'rejected' | 'timed-out' | 'unfinished' | 'unrouted' | 'blocked' | 'rate-limited' | 'circuit-open' | 'throttled' | 'unavailable' };
/** Component visits for one request, including the component where it failed without starting. */
export function traceSteps(result: SimulationResult, request: RequestRecord): TraceStep[] {
  const kinds = new Map(result.components.map(metric => [metric.id, metric.kind]));
  const isCache = (id: string) => CACHE_KINDS.has(kinds.get(id) as ComponentKind);
  const lastCache = request.processing.reduce((last, span, index) => isCache(span.component) ? index : last, -1);
  let previousEnd = request.arrivalTime;
  const steps: TraceStep[] = request.processing.map((span, index) => {
    const kind = kinds.get(span.component);
    const stepResult: TraceStep['result'] = span.note === 'read routed to replica' ? 'routed'
      : isCache(span.component) ? (index === lastCache && request.cache === 'hit' ? 'cache-hit' : 'cache-miss')
      : MESSAGING_KINDS.has(kind as ComponentKind) && request.status === 'completed' && index === request.processing.length - 1 && !request.internal ? 'enqueued'
        : request.status === 'failed' && request.failureKind === 'unfinished' && span.end > (request.completedAt ?? Infinity) ? 'unfinished' : 'processed';
    const step: TraceStep = { component: span.component, arrivedAt: previousEnd, start: span.start, end: span.end, wait: span.wait, note: span.note, result: stepResult };
    previousEnd = span.end; return step;
  });
  const last = request.processing.at(-1)?.component ?? request.origin;
  if (request.status === 'failed' && request.failedAt !== undefined) {
    const kind = request.failureKind ?? 'unrouted';
    const failure: TraceStep['result'] = kind === 'timeout' ? 'timed-out' : kind;
    const waitFrom = (request.redeliveredAt ?? []).reduce((latest, at) => at <= (request.completedAt ?? previousEnd) && at > latest ? at : latest, previousEnd);
    if (request.failedAt !== last) steps.push({ component: request.failedAt, arrivedAt: waitFrom, wait: (request.completedAt ?? waitFrom) - waitFrom, result: failure });
    else if (failure === 'blocked' && steps.length) steps[steps.length - 1].result = failure;
    else if (failure === 'unrouted') steps.push({ component: request.failedAt, arrivedAt: previousEnd, wait: 0, result: failure });
  }
  return steps;
}
