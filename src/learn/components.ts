/** Lesson id → title for written and planned lessons. */
const LESSON_TITLES = new Map(MODULES.flatMap(module => module.lessons.map(entry => [entry.id, entry.title] as const)));
const WRITTEN = new Set(LESSONS.map(lesson => lesson.id));
export type LessonLink = { id: string; title: string; written: boolean };

/** Everything known about a component: catalog contract + decision guide + LLD coverage + lessons. */
export type ComponentKnowledge = {
  kind: Kind; item: CatalogItem; guide: ComponentGuide;
  lld: { title: string; types: number } | null;
  /** Lessons that teach it: written lessons that reference the component, then the guide's concepts. */
  lessons: LessonLink[];
};
export function componentKnowledge(kind: Kind): ComponentKnowledge {
  const fromLessons = LESSONS.filter(lesson => lesson.components.includes(kind)).map(lesson => lesson.id);
  const ids = [...new Set([...GUIDES[kind].concepts, ...fromLessons])].filter(id => LESSON_TITLES.has(id));
  return {
    kind, item: byKind[kind], guide: GUIDES[kind], lld: LLD_COVERAGE[kind] ?? null,
    lessons: ids.map(id => ({ id, title: LESSON_TITLES.get(id)!, written: WRITTEN.has(id) })).sort((a, b) => Number(b.written) - Number(a.written)),
  };
}
